function pick(messages: string[]) {
  return messages[Math.floor(Math.random() * messages.length)];
}

export function submissionMessages(date: Date, totalMinutes: number, comment: string) {
  const hour = date.getHours();
  const period = hour >= 5 && hour < 11 ? "morning" : hour >= 11 && hour < 17 ? "daytime" : hour >= 17 && hour < 22 ? "evening" : "lateNight";
  const timeMessages = period === "morning" ? morning : period === "daytime" ? daytime : period === "evening" ? evening : lateNight;
  const hoursText = totalMinutes % 60 === 0
    ? `${Math.floor(totalMinutes / 60)}時間`
    : `${Math.floor(totalMinutes / 60)}時間${totalMinutes % 60}分`;
  const totalMessages = totalMinutes === 0 ? zeroHours : totalMinutes < 10 * 60 ? shortHours : totalMinutes < 20 * 60 ? mediumHours : totalMinutes < 30 * 60 ? longHours : veryLongHours;
  const normalizedComment = comment.normalize("NFKC").toLowerCase();
  const keywordMessage = /(葬儀|葬式|告別式|通夜|法事|法要|忌引|身内の不幸)/.test(normalizedComment)
    ? pick(condolenceMessages)
    : /(体調不良|風邪|発熱|熱が|病院|通院|療養|けが|怪我|入院|診察|治療)/.test(normalizedComment)
      ? pick(healthMessages)
      : /(疲れ|休みたい|休養|寝不足|睡眠不足)/.test(normalizedComment)
        ? pick(restMessages)
        : /(就活|就職活動|面接|説明会|インターン|選考)/.test(normalizedComment)
          ? pick(careerMessages)
          : /(授業|課題|レポート|実習|卒論|ゼミ)/.test(normalizedComment)
            ? pick(studyMessages)
            : /(試合|発表会|コンテスト|コンクール)/.test(normalizedComment)
              ? pick(competitionMessages)
              : /(引っ越し|引越し|転居|手続き|免許|教習所|新生活)/.test(normalizedComment)
                ? pick(lifeEventMessages)
                : /(家族|子ども|子供|送迎|介護|家の用事|家庭の用事)/.test(normalizedComment)
                  ? pick(familyMessages)
                  : /(テスト|試験|受験|模試|考査)/.test(normalizedComment)
                    ? pick(testMessages)
    : /(誕生日|記念日|バースデー)/.test(normalizedComment)
      ? pick(celebrationMessages)
      : /(文化祭|学園祭|体育祭|運動会|部活|合宿|大会|学校行事)/.test(normalizedComment)
        ? pick(schoolEventMessages)
        : /(旅行|帰省|遠征|温泉|観光)/.test(normalizedComment)
          ? pick(travelMessages)
          : /(遊び|ライブ|フェス|コンサート|推し活|デート)/.test(normalizedComment)
            ? pick(leisureMessages)
            : null;
  const totalTemplate = pick(totalMessages);
  const totalMessage = totalTemplate.includes("{hours}")
    ? totalTemplate.replaceAll("{hours}", hoursText).replaceAll("分分", "分")
    : `${totalTemplate}（希望合計：${hoursText}）`;
  return {
    greeting: pick(timeMessages),
    total: totalMessage,
    keyword: keywordMessage,
    hoursText,
    period,
  };
}
